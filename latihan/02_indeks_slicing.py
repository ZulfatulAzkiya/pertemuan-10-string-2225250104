
# Index dan Slicing pada String

teks = "MATEMATIKA"

print("Teks awal:", teks)
print("Karakter pertama:", teks[0])
print("Karakter ketiga:", teks[2])
print("Karakter terakhir:", teks[-1])

print("Tiga karakter pertama:", teks[:3])
print("Karakter indeks 2 sampai 5:", teks[2:6])
print("Dari indeks 4 sampai akhir:", teks[4:])
print("Teks terbalik:", teks[::-1])