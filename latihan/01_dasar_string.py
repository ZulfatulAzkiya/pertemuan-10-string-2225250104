
# Dasar-Dasar String Python

teks = "Belajar Pemrograman Python"

print("Teks:", teks)
print("Panjang teks:", len(teks))
print("Huruf pertama:", teks[0])
print("Huruf terakhir:", teks[-1])

print("Huruf besar:", teks.upper())
print("Huruf kecil:", teks.lower())
print("Huruf awal setiap kata:", teks.title())